// Reverse lookup map to quickly find SKU by Barcode
export const REVERSE_BARCODE_MAP: Record<string, string> = {};
Object.entries(BARCODE_MAP).forEach(([sku, barcode]) => {
  REVERSE_BARCODE_MAP[barcode] = sku;
  REVERSE_BARCODE_MAP[barcode.toUpperCase()] = sku;
});

let DYNAMIC_BARCODE_MAP: Record<string, string> = {};
let DYNAMIC_REVERSE_BARCODE_MAP: Record<string, string> = {};

export function updateDynamicBarcodeRegistry(items: { skuId: string; barcode?: string }[]) {
  const newMap: Record<string, string> = {};
  const newReverseMap: Record<string, string> = {};

  items.forEach(item => {
    if (item.skuId && item.barcode && item.barcode.trim() && item.barcode.trim() !== '-') {
      const cleanSku = item.skuId.trim().toUpperCase();
      const cleanBarcode = item.barcode.trim();
      newMap[cleanSku] = cleanBarcode;
      newReverseMap[cleanBarcode] = cleanSku;
      newReverseMap[cleanBarcode.toUpperCase()] = cleanSku;
    }
  });

  DYNAMIC_BARCODE_MAP = newMap;
  DYNAMIC_REVERSE_BARCODE_MAP = newReverseMap;
}

// Helper function to find SKU ID from either Barcode or SKU ID directly
export function findSkuId(input: string): string {
  if (!input) return "";
  const cleanInput = input.trim();
  const upperInput = cleanInput.toUpperCase();
  // Check dynamic reverse map first
  if (DYNAMIC_REVERSE_BARCODE_MAP[cleanInput]) {
    return DYNAMIC_REVERSE_BARCODE_MAP[cleanInput];
  }
  if (DYNAMIC_REVERSE_BARCODE_MAP[upperInput]) {
    return DYNAMIC_REVERSE_BARCODE_MAP[upperInput];
  }
  // Check static reverse map
  if (REVERSE_BARCODE_MAP[cleanInput]) {
    return REVERSE_BARCODE_MAP[cleanInput];
  }
  if (REVERSE_BARCODE_MAP[upperInput]) {
    return REVERSE_BARCODE_MAP[upperInput];
  }
  return cleanInput;
}

// Get barcode associated with SKU if available
export function getBarcodeForSku(skuId: string, explicitBarcode?: string): string {
  if (explicitBarcode && explicitBarcode.trim() && explicitBarcode.trim() !== '-') {
    return explicitBarcode.trim();
  }
  if (!skuId) return "-";
  const cleanId = skuId.trim().toUpperCase();
  if (DYNAMIC_BARCODE_MAP[cleanId]) {
    return DYNAMIC_BARCODE_MAP[cleanId];
  }
  return BARCODE_MAP[cleanId] || BARCODE_MAP[skuId] || "-";
}

// Use the product's explicit brand when available; leave it blank otherwise.
export function getProductBrand(skuId?: string, skuName?: string, explicitBrand?: string): string {
  if (explicitBrand && explicitBrand.trim()) {
    return explicitBrand.trim();
  }
  return '';
}

