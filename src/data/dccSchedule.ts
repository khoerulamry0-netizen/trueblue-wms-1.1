/**
 * Generate a perfectly balanced 5-day cycle count schedule from any SKU list
 * Distributes SKUs evenly across Senin, Selasa, Rabu, Kamis, Jumat.
 */
export function generateBalancedDccSchedule(skus: string[] = ALL_WAREHOUSE_SKUS): DaySchedule[] {
  const uniqueSkus = Array.from(new Set(skus)).sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));
  
  const scheduleMap: Record<DccDay, string[]> = {
    Senin: [],
    Selasa: [],
    Rabu: [],
    Kamis: [],
    Jumat: []
  };

  // Round-robin distribution ensures equal count and balanced product family mix
  uniqueSkus.forEach((sku, idx) => {
    const day = DCC_DAYS[idx % 5];
    scheduleMap[day].push(sku);
  });

  return DCC_DAYS.map(day => ({
    day,
    label: day,
    skus: scheduleMap[day]
  }));
}

// Pre-computed default schedule (260 SKUs / 5 = exactly 52 SKUs per day)
export const DCC_SCHEDULE: DaySchedule[] = generateBalancedDccSchedule(ALL_WAREHOUSE_SKUS);

export function getDccScheduleByDay(dayName: string, customSchedule: DaySchedule[] = DCC_SCHEDULE): string[] {
  const normDay = dayName.trim().toLowerCase();
  const dayMatch = customSchedule.find(d => d.day.toLowerCase() === normDay);
  return dayMatch ? dayMatch.skus : [];
}

export function getCurrentDayName(): DccDay {
  const days: DccDay[] = ['Senin', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Senin'];
  const dayIdx = new Date().getDay();
  return days[dayIdx] || 'Senin';
}
