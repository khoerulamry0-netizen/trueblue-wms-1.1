import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { findMigrationConflicts } from './check-migration-conflicts.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = path.join(root, 'supabase', 'migrations');
const outputPath = path.join(migrationsDir, '20261107100000_local_wms_operational.sql');
const checkOnly = process.argv.includes('--check');

const orderedSources = [
  'branch-schema.sql',
  'branch-sender-settings.sql',
  'branch-transfers.sql',
  'stock-consistency.sql',
  'operational-guard.sql',
  'activity-cancellations.sql',
  'basket-session-write-safety.sql',
  'order-stage-actors.sql',
  'order-import.sql',
  'order-import-no-expiry-marker.sql',
  'operational-guard-refinement.sql',
  'no-expiry-and-hq-reconciliation.sql',
  'backup-recovery.sql',
  'stock-purge-safety.sql',
  'reimport-cancelled-orders.sql',
  'period-archive.sql',
  'menu-audit-safety.sql',
  'hq-dashboard.sql',
  'hq-condition-alignment.sql',
  'viewer-network-read.sql',
  'admin-guard.sql',
];

const requiredOrder = [
  ['branch-schema.sql', 'branch-transfers.sql'],
  ['branch-transfers.sql', 'stock-consistency.sql'],
  ['stock-consistency.sql', 'activity-cancellations.sql'],
  ['stock-consistency.sql', 'operational-guard.sql'],
  ['activity-cancellations.sql', 'backup-recovery.sql'],
  ['backup-recovery.sql', 'stock-purge-safety.sql'],
  ['stock-purge-safety.sql', 'period-archive.sql'],
  ['stock-purge-safety.sql', 'menu-audit-safety.sql'],
  ['hq-dashboard.sql', 'hq-condition-alignment.sql'],
];

function assertSourceOrder() {
  const positions = new Map(orderedSources.map((file, index) => [file, index]));
  for (const [before, after] of requiredOrder) {
    if (positions.get(before) >= positions.get(after)) {
      throw new Error(`Invalid source dependency order: ${before} must precede ${after}`);
    }
  }
}

async function assemble() {
  assertSourceOrder();
  const chunks = [
    '-- Generated by scripts/build-local-migrations.mjs. Do not edit by hand.',
    '-- Local-development migration; production deployment is intentionally out of scope.',
    '-- Source SQL is retained under supabase/ for review and traceability.',
  ];

  for (const file of orderedSources) {
    const sourcePath = path.join(root, 'supabase', file);
    let sql = await readFile(sourcePath, 'utf8');
    if (file === 'admin-guard.sql') {
      const originalConstraint = 'check(active_count>=1)';
      if (!sql.includes(originalConstraint)) {
        throw new Error('admin-guard.sql changed: expected the zero-admin bootstrap constraint to be reviewed.');
      }
      sql = sql.replace(originalConstraint, 'check(active_count>=0)');
    }
    if (file === 'no-expiry-and-hq-reconciliation.sql') {
      const finalDashboard = await readFile(path.join(root, 'supabase', 'hq-condition-alignment.sql'), 'utf8');
      sql = removeRedundantDashboard(sql, finalDashboard);
    }
    sql = terminateFinalFunction(sql, file);
    chunks.push(`\n-- >>> ${file}\n${sql.trimEnd()}\n-- <<< ${file}`);
  }

  return `${chunks.join('\n\n')}\n`;
}

function getFunctionDefinitions(sql) {
  const definitions = [];
  const declaration = /\bcreate\s+(?:or\s+replace\s+)?function\s+(?:public|wms_private)\.([a-z0-9_]+)\s*\([\s\S]*?\)\s*returns\b/gi;
  for (const match of sql.matchAll(declaration)) {
    const start = match.index;
    const rest = sql.slice(start + match[0].length);
    const delimiter = rest.match(/\bas\s+(\$[a-z0-9_]*\$)/i)?.[1];
    if (!delimiter) throw new Error(`Cannot locate function body delimiter for ${match[1]}.`);
    const bodyStart = start + match[0].length + rest.indexOf(delimiter) + delimiter.length;
    const bodyEnd = sql.indexOf(delimiter, bodyStart);
    if (bodyEnd < 0) throw new Error(`Unterminated function body for ${match[1]}.`);
    definitions.push({
      name: match[1].toLowerCase(),
      body: sql.slice(bodyStart, bodyEnd).toLowerCase(),
      start,
      end: bodyEnd + delimiter.length,
    });
  }
  return definitions;
}

function withoutLeadingTrivia(sql) {
  return sql.replace(/^(?:\s|--[^\r\n]*(?:\r?\n|$)|\/\*[\s\S]*?\*\/)*/, '');
}

export function removeRedundantDashboard(source, finalSource) {
  const definitions = getFunctionDefinitions(source).filter((entry) => entry.name === 'hq_dashboard');
  if (definitions.length !== 1) throw new Error('Expected exactly one early HQ dashboard definition.');
  const definition = definitions[0];
  const after = source.slice(definition.end);
  const semicolon = after.match(/^\s*;/);
  if (!semicolon || withoutLeadingTrivia(after.slice(semicolon[0].length))) {
    throw new Error('Expected the early HQ dashboard to be the final source statement.');
  }
  const end = definition.end + semicolon[0].length;
  if (source.slice(definition.start, end).trim() !== finalSource.trim()) {
    throw new Error('Early and final HQ dashboard definitions differ; review before consolidating.');
  }
  return source.slice(0, definition.start) + source.slice(end);
}

export function terminateFinalFunction(sql, sourceName) {
  for (const definition of getFunctionDefinitions(sql)) {
    const following = withoutLeadingTrivia(sql.slice(definition.end));
    if (following.startsWith(';')) continue;
    if (following.length > 0) {
      throw new Error(`Missing SQL terminator after function ${definition.name} in ${sourceName}.`);
    }
    sql = `${sql.slice(0, definition.end)};${sql.slice(definition.end)}`;
  }
  return sql;
}

export function verifyFunctionTerminators(sql, sourceName) {
  for (const definition of getFunctionDefinitions(sql)) {
    if (!withoutLeadingTrivia(sql.slice(definition.end)).startsWith(';')) {
      throw new Error(`Missing SQL terminator after function ${definition.name} in ${sourceName}.`);
    }
  }
}

async function verify(sql) {
  const files = (await readdir(migrationsDir)).filter((name) => /^\d{14}_.+\.sql$/.test(name)).sort();
  if (!files.includes('20261105000000_unified_wms.sql')) {
    throw new Error('The original unified WMS migration is missing.');
  }
  if (files.indexOf('20261107100000_local_wms_operational.sql') <= files.indexOf('20261105000000_unified_wms.sql')) {
    throw new Error('The local operational migration must follow the unchanged initial migration.');
  }

  verifyFunctionTerminators(sql, path.basename(outputPath));
  const originalMigration = await readFile(path.join(migrationsDir, '20261105000000_unified_wms.sql'), 'utf8');
  verifyFunctionTerminators(originalMigration, '20261105000000_unified_wms.sql');
  const migrations = await Promise.all(files.map(async (name) => ({
    name,
    sql: name === path.basename(outputPath) ? sql : await readFile(path.join(migrationsDir, name), 'utf8'),
  })));
  const conflicts = findMigrationConflicts(migrations);
  if (conflicts.length) throw new Error(`Migration object conflicts:\n${conflicts.join('\n')}`);
  const definitions = getFunctionDefinitions(sql);
  const finalBody = (name) => definitions.filter((definition) => definition.name === name).at(-1)?.body ?? '';
  const sections = orderedSources.map((file) => ({
    file,
    start: sql.indexOf(`-- >>> ${file}`),
  }));
  const finalDefinitionSection = (name) => {
    const definition = definitions.filter((entry) => entry.name === name).at(-1);
    return sections.filter((section) => section.start <= definition.start).at(-1)?.file;
  };
  const intendedFinalSections = [
    ['validate_operational_write', 'menu-audit-safety.sql'],
    ['import_wms_orders', 'reimport-cancelled-orders.sql'],
    ['commit_wms_write', 'basket-session-write-safety.sql'],
    ['branch_transfer_action', 'activity-cancellations.sql'],
    ['hq_dashboard', 'hq-condition-alignment.sql'],
  ];
  for (const [functionName, expectedSection] of intendedFinalSections) {
    if (finalDefinitionSection(functionName) !== expectedSection) {
      throw new Error(`Unexpected overriding definition for ${functionName}; expected ${expectedSection} to be final.`);
    }
  }
  const requiredFinalFeatures = [
    ['validate_operational_write', 'perform wms_private.validate_menu_audit_write'],
    ['validate_operational_write', 'pengosongan stok harus melalui autentikasi ulang'],
    ['import_wms_orders', 'reimp_'],
    ['import_wms_orders', 'wms_private.stock_pickable'],
    ['commit_wms_write', 'expected_revision'],
    ['commit_wms_write', 'pg_advisory_xact_lock'],
    ['commit_wms_write', 'current_revision'],
    ['commit_wms_write', 'pt409'],
    ['commit_wms_write', 'wms_private.can_access_branch'],
    ['commit_wms_write', 'validate_operational_write'],
    ['branch_transfer_action', 'wms_private.can_access_branch'],
    ['branch_transfer_action', 'for update'],
    ['hq_dashboard', 'not wms_private.is_hq()'],
    ['hq_dashboard', "'hold_qty'"],
  ];

  for (const [functionName, feature] of requiredFinalFeatures) {
    if (!finalBody(functionName).includes(feature)) {
      throw new Error(`Final ${functionName} definition is missing required behavior: ${feature}`);
    }
  }

  const requiredPublicRpcs = [
    'commit_wms_write',
    'import_wms_orders',
    'branch_transfer_action',
    'cancel_wms_orders',
    'branch_backup_action',
    'hq_dashboard',
    'period_archive_action',
    'stock_purge_action',
  ];
  for (const rpc of requiredPublicRpcs) {
    if (!new RegExp(`\\bcreate\\s+(?:or\\s+replace\\s+)?function\\s+public\\.${rpc}\\s*\\(`, 'i').test(sql)) {
      throw new Error(`Frontend RPC contract is missing public.${rpc}.`);
    }
    if (!new RegExp(`\\bgrant\\s+execute\\s+on\\s+function\\s+public\\.${rpc}\\s*\\(`, 'i').test(sql)) {
      throw new Error(`Authenticated EXECUTE grant is missing for public.${rpc}.`);
    }
  }

  const directGrant = sql.toLowerCase().lastIndexOf(
    'grant select,insert,update,delete on public.wms_documents to authenticated',
  );
  const directRevoke = sql.toLowerCase().lastIndexOf(
    'revoke insert,update,delete on public.wms_documents from authenticated',
  );
  if (directGrant < 0 || directRevoke < directGrant) {
    throw new Error('Direct WMS document write grants are not revoked after the branch schema grants them.');
  }
  if (!sql.toLowerCase().includes('revoke all on function public.apply_wms_batch(jsonb,jsonb,text)')) {
    throw new Error('The branch-scoped legacy batch RPC is not disabled.');
  }

  const adminGuard = sql.slice(sql.toLowerCase().lastIndexOf('-- >>> admin-guard.sql')).toLowerCase();
  if (!adminGuard.includes('check(active_count>=0)')) {
    throw new Error('The local admin guard must permit a zero-admin database before authenticated bootstrap.');
  }

  const sourcePositions = sections.map((section) => section.start);
  if (sourcePositions.some((position) => position < 0) || sourcePositions.some((position, i) => i > 0 && position <= sourcePositions[i - 1])) {
    throw new Error('Generated migration source sections are missing or out of order.');
  }
}

async function main() {
  const generated = await assemble();
  await verify(generated);

  if (checkOnly) {
    if (!(await readdir(migrationsDir)).includes(path.basename(outputPath))) {
      throw new Error('The generated local migration is missing.');
    }
    const existing = await readFile(outputPath, 'utf8');
    if (existing !== generated) {
      console.error('Local migration is stale. Run npm run supabase:local:migrations to regenerate it.');
      process.exitCode = 1;
    } else {
      console.log(`Static migration checks passed: ${path.basename(outputPath)}`);
    }
  } else {
    await writeFile(outputPath, generated, 'utf8');
    console.log(`Generated ${path.relative(root, outputPath)}; no database commands were run.`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
